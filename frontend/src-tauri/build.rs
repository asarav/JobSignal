//! Build script: generate the IPC method allowlist from the schema registry.
//!
//! `schemas/ipc/methods.json` is emitted by `scripts/gen_schemas.py` and is the
//! single source of truth shared by Python, TypeScript and Rust. Rust never
//! hard-codes method names, so a method that is not in the schema registry can
//! never be forwarded to the worker.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    tauri_build::build();

    // `tauri-build` embeds a Common Controls v6 manifest in the application
    // binary. The lib test binary is linked separately and imports
    // `TaskDialogIndirect`; without the same manifest Windows loads comctl32
    // v5 and the test process dies before `main` with STATUS_ENTRYPOINT_NOT_FOUND.
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .join("tests.manifest");
    println!("cargo:rerun-if-changed={}", manifest.display());
    if cfg!(windows) {
        println!("cargo:rustc-link-arg-tests=/MANIFEST:EMBED");
        println!(
            "cargo:rustc-link-arg-tests=/MANIFESTINPUT:{}",
            manifest.display()
        );
    }

    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let methods_path = manifest_dir.join("../../schemas/ipc/methods.json");
    println!("cargo:rerun-if-changed={}", methods_path.display());

    let text = fs::read_to_string(&methods_path).unwrap_or_else(|error| {
        panic!(
            "failed to read {}: {error}\nRun: python scripts/gen_schemas.py",
            methods_path.display()
        )
    });
    let catalogue: serde_json::Value =
        serde_json::from_str(&text).expect("schemas/ipc/methods.json is not valid JSON");

    let protocol_version = catalogue["protocol_version"]
        .as_u64()
        .expect("methods.json is missing protocol_version");
    let methods = catalogue["methods"]
        .as_array()
        .expect("methods.json is missing methods[]");
    let forbidden = catalogue["forbidden_prefixes"]
        .as_array()
        .expect("methods.json is missing forbidden_prefixes[]");

    let mut generated = String::new();
    generated.push_str("// @generated by build.rs from schemas/ipc/methods.json.\n");
    generated.push_str("// Do not edit by hand; run `python scripts/gen_schemas.py`.\n\n");
    generated.push_str(&format!(
        "pub const PROTOCOL_VERSION: u32 = {protocol_version};\n\n"
    ));

    generated.push_str("pub const ALLOWED_METHODS: &[&str] = &[\n");
    for method in methods {
        let name = method["method"]
            .as_str()
            .expect("methods[] entry is missing a string `method`");
        generated.push_str(&format!("    {name:?},\n"));
    }
    generated.push_str("];\n\n");

    generated.push_str("pub const FORBIDDEN_PREFIXES: &[&str] = &[\n");
    for prefix in forbidden {
        let value = prefix
            .as_str()
            .expect("forbidden_prefixes[] entry must be a string");
        generated.push_str(&format!("    {value:?},\n"));
    }
    generated.push_str("];\n");

    // How long the shell waits for each method. Most methods are one HTTP
    // budget; a crawl or a discovery pass is not, and a fixed 60 s wait used to
    // abandon work that was still running.
    generated.push_str("pub const METHOD_TIMEOUTS: &[(&str, u64)] = &[");
    generated.push('\n');
    for method in methods {
        let name = method["method"]
            .as_str()
            .expect("methods[] entry is missing a string `method`");
        let seconds = method["timeout_s"].as_f64().unwrap_or(60.0);
        generated.push_str(&format!("    ({name:?}, {}),", seconds.round() as u64));
        generated.push('\n');
    }
    generated.push_str("];");
    generated.push('\n');

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("allowlist.rs"), generated).expect("failed to write allowlist.rs");
}
